#include "riscv-macros.h"

TEST_RISCV_BEGIN

  #--------------------------------------------------------------------
  # Setup: 三個位址 A, B, C 都 map 到同一個 set
  #   A = base
  #   B = base + 2048   (2^11)
  #   C = base + 4096   (2^12)
  #--------------------------------------------------------------------

  la   x1, set_base        # x1 = base (A)

  li   x2, 2048            # 2^11
  add  x9, x1, x2          # x9 = B = base + 2048

  li   x3, 4096            # 2^12
  add  x10, x1, x3         # x10 = C = base + 4096

  #--------------------------------------------------------------------
  # 初始化 memory：把 A/B/C 設好值
  #--------------------------------------------------------------------

  li   x11, 0xAAA11111
  sw   x11, 0(x1)          # mem[A] = 0xAAA11111

  li   x12, 0xBBB22222
  sw   x12, 0(x9)          # mem[B] = 0xBBB22222

  li   x13, 0xCCC33333
  sw   x13, 0(x10)         # mem[C] = 0xCCC33333

  #--------------------------------------------------------------------
  # Step 1: 把 A、B 讀進 cache（兩個 miss → 塞滿這個 set）
  #--------------------------------------------------------------------

  lw   x4, 0(x1)           # load A
  lw   x5, 0(x9)           # load B

  #--------------------------------------------------------------------
  # Step 2: 再讀一次 A，讓「B 變成 LRU」
  #--------------------------------------------------------------------

  lw   x4, 0(x1)           # A hit，LRU bit 更新

  #--------------------------------------------------------------------
  # Step 3: 把 A 寫成新值（dirty + MRU）
  #--------------------------------------------------------------------

  li   x6, 0xAAA99999
  sw   x6, 0(x1)           # A 變成 0xAAA99999，且 dirty

  #--------------------------------------------------------------------
  # Step 4: 讀 C → miss，需要 eviction，會走到 LRU victim 路徑
  #         這裡會測到：victim 選取 + write-back + refill
  #--------------------------------------------------------------------

  lw   x7, 0(x10)          # load C，造成這個 set 的第一次 eviction

  #--------------------------------------------------------------------
  # Step 5: 再多刷幾次同一個 set，讓 LRU bit 不斷翻轉
  #--------------------------------------------------------------------

  lw   x4, 0(x1)           # A
  lw   x5, 0(x9)           # B
  lw   x7, 0(x10)          # C
  lw   x4, 0(x1)           # A 再 hit 一次

  #--------------------------------------------------------------------
  # Step 6: 最終檢查：所有 A/B/C 的值都要正確
  #         （代表多次 eviction / refill / dirty-writeback 都沒壞）
  #--------------------------------------------------------------------

  lw   x14, 0(x1)
  TEST_CHECK_EQ( x14, 0xAAA99999 )

  lw   x15, 0(x9)
  TEST_CHECK_EQ( x15, 0xBBB22222 )

  lw   x16, 0(x10)
  TEST_CHECK_EQ( x16, 0xCCC33333 )

TEST_RISCV_END

  .section .data
  .align 6
set_base:
  .space 8192              # 給我們 A/B/C 玩，同一個 data 區塊
